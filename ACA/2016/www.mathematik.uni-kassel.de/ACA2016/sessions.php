<h2>Call for Sessions</h2>
<p class="left">The 22nd International Conference on Applications of Computer Algebra 
(ACA, <a href="http://math.unm.edu/~aca" target="_blank">http://math.unm.edu/~aca</a>) will take place in Kassel (Germany) on 
August 1-4, 2016. The ACA conferences are organized as a series of 
Special Sessions. All interested researchers can propose a Special 
Session by sending an e-mail to the Program Chairs 
(<a href="javascript:mailMe('aca2016chairs');">aca2016chairs(at)mathematik.uni-kassel.de</a>) by March 31st, 2016. The 
Scientific Committee (i.e. the ACA Working Group) will then decide on 
the acceptance of the proposed session. Accepted sessions will be 
immediately announced on the this site 
</p>

<class="left">
A proposal for a Special Session has to include:
<ul>
	<li>title of the Special Session,</li>
	<li>short abstract describing the Special Session,</li>
	<li>contact information of the organizers.</li>
</ul>
</p>

<class="left">
For more details see 
<a href="http://math.unm.edu/ACA/Organizing/special_session.html">http://math.unm.edu/ACA/Organizing/special_session.html</a>
</p>

<class="left">
Talk submissions have to be directed to the organizers of an appropriate 
Special Session. It is expected that organizers actively contact 
potential speakers.
</p>
