<h2>Visa</h2>
Participants from outside of Europe will most probably need a visa to
enter Germany. Please inform yourself at a German embassy/consulate
about the precise procedure and take into account that visa applications
typically require quite some time to be processed. If you need a letter
of invitation, write after your registration an e-mail to
aca2016(at)mathematik.uni-kassel.de containing your full name and the
address to which the letter should be sent (we send letters only to your
private or work address, not directly to embassies or consulates). If
you plan to give a talk, then also include the title of your talk. We
will then send you the letter by mail and a scan of the letter by
e-mail. Note, however, that the German authorities often do not accept a
scan. Thus you should also take into account the time required by a
letter from Germany to your country. Please understand that we can
provide letters of invitation only for registered participants.
